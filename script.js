let selectedGenre = "";

const container = document.getElementById("story-container");
const homePage = document.getElementById("home");
const storiesSection = document.getElementById("stories");
const chapterView = document.getElementById("chapter-view");
const chapterContent = document.getElementById("chapter-content");
const genreTitle = document.getElementById("genre-title");

// SHOW BOOK COVERS AFTER SELECTING A GENRE
function showGenre(genre) {
  selectedGenre = genre;

  const genreNames = {
    romance: "Romance Books",
    horror: "Horror Books",
    fantasy: "Fantasy Books"
  };

  genreTitle.textContent = genreNames[genre] || "Books";
  container.innerHTML = "";

  stories.forEach((story, index) => {
    if (story.genre.toLowerCase() !== genre.toLowerCase()) {
      return;
    }

    const card = document.createElement("button");
    card.type = "button";
    card.className = "story-card";
    card.setAttribute("aria-label", "Read " + story.title);

    card.innerHTML = `
      <img src="${story.image}" alt="${story.title} cover">
      <h3>${story.title}</h3>
    `;

    card.addEventListener("click", () => {
      viewChapter(index);
    });

    container.appendChild(card);
  });

  homePage.hidden = true;
  chapterView.hidden = true;
  storiesSection.hidden = false;

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

// SHOW CHAPTER 1 AFTER CLICKING A BOOK COVER
function viewChapter(index) {
  const story = stories[index];

  if (!story) return;

  chapterContent.innerHTML = "";

  // STORY TITLE
  const title = document.createElement("h2");
  title.textContent = story.title;
  chapterContent.appendChild(title);

  // SYNOPSIS
  const synopsisHeading = document.createElement("h3");
  synopsisHeading.textContent = "Synopsis";
  chapterContent.appendChild(synopsisHeading);

  const synopsisText = document.createElement("p");
  synopsisText.textContent = story.synopsis || "Synopsis is not available yet.";
  chapterContent.appendChild(synopsisText);

  // CHAPTER 1
  const chapterHeading = document.createElement("h3");
  chapterHeading.textContent = "Chapter 1";
  chapterContent.appendChild(chapterHeading);

  const chapterText = document.createElement("p");
  chapterText.textContent =
    story.chapter1 && story.chapter1.trim()
      ? story.chapter1
      : "Chapter 1 is not available yet.";
  chapterContent.appendChild(chapterText);

  // SHOW CHAPTER VIEW
  storiesSection.hidden = true;
  homePage.hidden = true;
  chapterView.hidden = false;

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

